// HELPERS
// ═══════════════════════════════════════════════════════════════════════════════

function humanCategory(cat) {
  const map = {
    'banners': 'Banners',
    'banner-images': 'Banners',
    'events': 'Events',
    'characters': 'Resonators',
    'weapons': 'Weapons',
    'enrichment': 'Data',
    'data-enrichment': 'Data',
    'meta-refresh': 'Builds',
    'standard-pool': 'Standard Pool',
    'images': 'Images',
    'health': 'Maintenance',
    'version': 'Version',
    'evolution': 'Agent',
    'evolution-create': 'Agent',
    'shell-swap': 'Agent',
    'ui-polish': 'UI',
    'bugfix': 'Fixes',
    'code-quality': 'Code',
    'feature': 'Features',
    'a11y': 'Accessibility',
    'rollback-warning': 'Warning',
  };
  return map[cat] || cat;
}

function cleanDescription(desc) {
  // Remove technical prefixes and make user-friendly
  return desc
    .replace(/^\[evolution\]\s*/i, '')
    .replace(/^Shell-swap:\s*/i, '')
    .replace(/^Bump version\s*/i, 'Updated to ')
    .replace(/^Added\s+/i, 'Added ')
    .replace(/^Updated\s+/i, 'Updated ')
    .replace(/→/g, '→')
    .slice(0, 120);
}
